#!/usr/bin/env python3
"""Writes a table of the catalog's translations for a native speaker to skim (spec 2.5 "Translation process").

    python3 app/scripts/l10n-review.py --lang tr      # -> docs/l10n/review-tr.md
    python3 app/scripts/l10n-review.py --lang it      # -> docs/l10n/review-it.md
    python3 app/scripts/l10n-review.py --lang tr --out /tmp/review-tr.md

Columns: key | en | translation | file. `en` is the source text (the key itself, or the catalog's own English string when the key
has plural or positional forms). `file` is the Swift file the key is used in, read from the `.stringsdata` files a build leaves
under app/.build (run `swift build` first; without them the column says `?`). Corrections go straight into the catalog
(`Localizable.xcstrings`); this review never blocks shipping.
"""
import argparse
import json
import sys
from pathlib import Path

APP = Path(__file__).resolve().parent.parent
REPO = APP.parent
CATALOG = APP / "Sources" / "VerseUI" / "Resources" / "Localizable.xcstrings"


def unit_text(loc: dict) -> str:
    """One display string for a localization: plain, or `one / other` for plural forms."""
    if not loc:
        return ""
    if "stringUnit" in loc:
        return loc["stringUnit"].get("value", "")
    plural = (loc.get("variations") or {}).get("plural")
    if plural:
        forms = [plural[k]["stringUnit"]["value"] for k in ("one", "other") if k in plural]
        # Languages that use one form for both (Turkish) show it once.
        return forms[0] if len(set(forms)) == 1 else "  /  ".join(forms)
    return ""


def key_files(build_dir: Path) -> dict[str, set[str]]:
    """key -> the Swift files that use it, from the `.stringsdata` files of VerseUI and VerseApp."""
    out: dict[str, set[str]] = {}
    for f in build_dir.rglob("*.stringsdata"):
        parts = f.as_posix()
        if "VerseUITests" in parts or not ("/VerseUI-" in parts or "/Verse-p.build/" in parts):
            continue
        try:
            data = json.loads(f.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        name = Path(data.get("source", "")).name
        for entries in (data.get("tables") or {}).values():
            for e in entries:
                out.setdefault(e.get("key", ""), set()).add(name)
    return out


def cell(s: str) -> str:
    return s.replace("|", "\\|").replace("\n", " ⏎ ")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--lang", required=True, choices=("tr", "it"))
    ap.add_argument("--out", type=Path)
    ap.add_argument("--catalog", type=Path, default=CATALOG)
    args = ap.parse_args()

    data = json.loads(args.catalog.read_text(encoding="utf-8"))
    files = key_files(APP / ".build")
    rows = []
    for key, entry in sorted(data.get("strings", {}).items(), key=lambda kv: kv[0].lower()):
        if key == "" or entry.get("shouldTranslate") is False or entry.get("extractionState") == "stale":
            continue
        locs = entry.get("localizations") or {}
        en = unit_text(locs.get("en", {})) or key
        tr = unit_text(locs.get(args.lang, {}))
        where = ", ".join(sorted(files.get(key, ()))) or "?"
        rows.append((key, en, tr, where))

    names = {"tr": "Turkish", "it": "Italian"}
    lines = [
        f"# {names[args.lang]} translations for review",
        "",
        f"{len(rows)} strings. Edit the translation in `app/Sources/VerseUI/Resources/Localizable.xcstrings` (or tell Claude the change). "
        "Terms are fixed in `docs/l10n-glossary.md`. Generated by `app/scripts/l10n-review.py`.",
        "",
        "| key | en | " + args.lang + " | file |",
        "|---|---|---|---|",
    ]
    for key, en, tr, where in rows:
        shown_key = key if key != en else "="
        lines.append(f"| {cell(shown_key)} | {cell(en)} | {cell(tr)} | {where} |")
    text = "\n".join(lines) + "\n"
    out = args.out or (REPO / "docs" / "l10n" / f"review-{args.lang}.md")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8")
    print(f"l10n-review: {len(rows)} strings -> {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
