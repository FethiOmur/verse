import AppKit
import ApplicationServices
import Carbon.HIToolbox
import Foundation

/// What became of a dictated text.
public enum DictationInsertOutcome: String, Sendable, Equatable {
    /// Pasted into the app in front.
    case pasted
    /// No Accessibility permission: the text was left on the clipboard for the owner to paste.
    case copiedToClipboard
    /// Nothing to insert.
    case nothing
}

/// Puts dictated text where the keyboard focus is.
@MainActor
public protocol DictationTextInserting: AnyObject {
    /// `mayPromptForPermission`: when the Accessibility permission is missing, ask the system to show its prompt.
    func insert(_ text: String, mayPromptForPermission: Bool) async -> DictationInsertOutcome
}

/// The Accessibility permission check (`AXIsProcessTrusted`). Fake in tests.
@MainActor
public protocol AccessibilityTrust: AnyObject {
    /// `prompt`: ask the system to show its Accessibility prompt when the permission is missing (it returns at once).
    func isTrusted(prompt: Bool) -> Bool
}

/// Every item on the pasteboard with every type's data, so it can be put back as it was.
public struct PasteboardSnapshot: Sendable, Equatable {
    public var items: [[String: Data]]
    public init(items: [[String: Data]]) { self.items = items }
}

/// The general pasteboard. Fake in tests.
@MainActor
public protocol DictationPasteboard: AnyObject {
    var changeCount: Int { get }
    func snapshot() -> PasteboardSnapshot
    /// Replaces the contents with `text`. `transient` marks it for clipboard managers as not worth keeping
    /// (nspasteboard.org's TransientType/AutoGeneratedType). Returns the new change count.
    @discardableResult func write(_ text: String, transient: Bool) -> Int
    func restore(_ snapshot: PasteboardSnapshot)
}

/// The synthesised ⌘V. Fake in tests.
@MainActor
public protocol PasteKeystroke: AnyObject {
    /// Waits (bounded) until the hot key's modifiers are released, so they do not mix into the paste.
    func waitForModifierRelease() async
    func postPaste()
}

/// Inserts by pasteboard plus a synthesised ⌘V, then puts the previous pasteboard back.
///
/// Chosen over synthesised typing (`CGEvent.keyboardSetUnicodeString`): a paste arrives as one edit, so Turkish letters,
/// emoji and composed characters come through exactly; a line break stays a line break (typed, it is a Return key that sends
/// the message in chat apps); the speed does not depend on the text's length; and it does not depend on the keyboard layout.
/// What it costs is the pasteboard, so the previous contents are saved with every type and restored after the target app had
/// time to read the paste, unless something else was copied in between.
@MainActor
public final class PasteboardTextInserter: DictationTextInserting {
    /// How long the target app gets to read the pasteboard before the previous contents come back.
    public static let defaultRestoreDelay: Duration = .milliseconds(600)

    private let accessibility: any AccessibilityTrust
    private let pasteboard: any DictationPasteboard
    private let keystroke: any PasteKeystroke
    private let restoreDelay: Duration
    private let sleep: @Sendable (Duration) async -> Void

    public init(accessibility: (any AccessibilityTrust)? = nil, pasteboard: (any DictationPasteboard)? = nil,
                keystroke: (any PasteKeystroke)? = nil, restoreDelay: Duration = PasteboardTextInserter.defaultRestoreDelay,
                sleep: @escaping @Sendable (Duration) async -> Void = { try? await Task.sleep(for: $0) }) {
        self.accessibility = accessibility ?? SystemAccessibilityTrust()
        self.pasteboard = pasteboard ?? SystemDictationPasteboard()
        self.keystroke = keystroke ?? CGPasteKeystroke()
        self.restoreDelay = restoreDelay
        self.sleep = sleep
    }

    public func insert(_ text: String, mayPromptForPermission: Bool) async -> DictationInsertOutcome {
        guard !text.isEmpty else { return .nothing }
        // Without the permission a synthesised key event is dropped silently: leave the text on the clipboard instead.
        guard accessibility.isTrusted(prompt: mayPromptForPermission) else {
            pasteboard.write(text, transient: false)
            return .copiedToClipboard
        }
        let saved = pasteboard.snapshot()
        let ours = pasteboard.write(text, transient: true)
        await keystroke.waitForModifierRelease()
        keystroke.postPaste()
        await sleep(restoreDelay)
        // Something copied meanwhile (by the owner or another app) is newer than what was saved: it stays.
        if pasteboard.changeCount == ours { pasteboard.restore(saved) }
        return .pasted
    }
}

/// `AXIsProcessTrusted`, with the system prompt on request.
final class SystemAccessibilityTrust: AccessibilityTrust {
    func isTrusted(prompt: Bool) -> Bool {
        guard prompt else { return AXIsProcessTrusted() }
        // The value of kAXTrustedCheckOptionPrompt (the global itself is not concurrency-safe to read in Swift 6).
        return AXIsProcessTrustedWithOptions(["AXTrustedCheckOptionPrompt": true] as CFDictionary)
    }
}

/// `NSPasteboard.general`.
final class SystemDictationPasteboard: DictationPasteboard {
    private var pb: NSPasteboard { .general }
    static let transientMarkers = ["org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]

    var changeCount: Int { pb.changeCount }

    func snapshot() -> PasteboardSnapshot {
        PasteboardSnapshot(items: (pb.pasteboardItems ?? []).map { item in
            var d: [String: Data] = [:]
            for t in item.types { if let v = item.data(forType: t) { d[t.rawValue] = v } }
            return d
        })
    }

    @discardableResult
    func write(_ text: String, transient: Bool) -> Int {
        pb.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        if transient { for m in Self.transientMarkers { item.setData(Data(), forType: NSPasteboard.PasteboardType(m)) } }
        pb.writeObjects([item])
        return pb.changeCount
    }

    func restore(_ snapshot: PasteboardSnapshot) {
        pb.clearContents()
        let items = snapshot.items.map { dict in
            let item = NSPasteboardItem()
            for (type, data) in dict { item.setData(data, forType: NSPasteboard.PasteboardType(type)) }
            return item
        }
        if !items.isEmpty { pb.writeObjects(items) }
    }
}

/// ⌘V as two HID-level key events. kVK_ANSI_V is a physical key position: V on the US, Italian and Turkish Q layouts.
final class CGPasteKeystroke: PasteKeystroke {
    func waitForModifierRelease() async {
        let held: CGEventFlags = [.maskCommand, .maskAlternate, .maskControl, .maskShift]
        for _ in 0..<50 {   // at most a second
            if CGEventSource.flagsState(.combinedSessionState).intersection(held).isEmpty { return }
            try? await Task.sleep(for: .milliseconds(20))
        }
    }

    func postPaste() {
        let source = CGEventSource(stateID: .hidSystemState)
        for down in [true, false] {
            let e = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down)
            e?.flags = .maskCommand
            e?.post(tap: .cghidEventTap)
        }
    }
}
